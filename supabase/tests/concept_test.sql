-- Concept tests: who may ask for concepts, limits, worker claim/complete, design freeze and change control.
-- Runs after kb_test.sql (users: a owner, b outsider, c engineer, d reviewer, e viewer, f client of project bbbb...1).
\set ON_ERROR_STOP on
\o /dev/null

create function pg_temp.act_as(p_user uuid) returns void language plpgsql as $$
begin
  perform set_config('request.jwt.claim.sub', coalesce(p_user::text, ''), false);
  if p_user is null then execute 'reset role'; else execute 'set role authenticated'; end if;
end;
$$;
create function pg_temp.as_worker() returns void language plpgsql as $$
begin
  perform set_config('request.jwt.claim.sub', '', false);
  execute 'set role service_role';
end;
$$;
create function pg_temp.expect_error(p_sql text, p_like text) returns void language plpgsql as $$
declare v_err text;
begin
  begin execute p_sql; exception when others then v_err := sqlerrm; end;
  if v_err is null then raise exception 'statement should have failed but succeeded: %', p_sql;
  elsif v_err not like p_like then raise exception 'expected error like "%", got "%"', p_like, v_err; end if;
end;
$$;
create function pg_temp.check(p_ok boolean, p_msg text) returns void language plpgsql as $$
begin if not coalesce(p_ok, false) then raise exception 'check failed: %', p_msg; end if; end;
$$;
create temp table ids (name text primary key, id uuid);
grant all on ids to authenticated, service_role;
create function pg_temp.id(p_name text) returns uuid language sql as $$ select id from ids where name = p_name $$;
create function pg_temp.variants(p_project uuid, p_n integer) returns jsonb language sql as $$
  select jsonb_agg(jsonb_build_object('ordinal', i, 'name', 'Variant ' || i, 'prompt', 'a slate, variant ' || i,
         'cmf', jsonb_build_object('summary', 'matte black'), 'status', 'ready', 'image_path', p_project || '/concepts/x/' || i || '.png',
         'mime_type', 'image/png', 'sha256', md5(i::text), 'provider', 'fixture', 'model', 'fixture-1'))
    from generate_series(1, p_n) i
$$;

-- 1. Who may ask.
select pg_temp.act_as('00000000-0000-0000-0000-00000000000e');   -- viewer
select pg_temp.expect_error($$select public.request_concepts('bbbbbbbb-0000-0000-0000-000000000001', 'rugged', 3)$$, '%only owners, engineers and clients%');
select pg_temp.act_as('00000000-0000-0000-0000-00000000000b');   -- outsider
select pg_temp.expect_error($$select public.request_concepts('bbbbbbbb-0000-0000-0000-000000000001', 'rugged', 3)$$, '%only owners, engineers and clients%');
select pg_temp.act_as('00000000-0000-0000-0000-00000000000f');   -- client
select pg_temp.expect_error($$select public.request_concepts('bbbbbbbb-0000-0000-0000-000000000001', '  ', 3)$$, '%describe the direction%');
select pg_temp.expect_error($$select public.request_concepts('bbbbbbbb-0000-0000-0000-000000000001', 'rugged', 5)$$, '%1 to 4 variants%');
insert into ids select 'r1', public.request_concepts('bbbbbbbb-0000-0000-0000-000000000001', 'Rugged, matte black, one-hand use', 3);
select pg_temp.check((select round_no = 1 and status = 'queued' and requested_by = '00000000-0000-0000-0000-00000000000f'
                      from public.concept_rounds where id = pg_temp.id('r1')), 'client asked for round 1');
select pg_temp.act_as('00000000-0000-0000-0000-00000000000c');   -- engineer
insert into ids select 'r2', public.request_concepts('bbbbbbbb-0000-0000-0000-000000000001', 'Slim, brushed aluminium', 2);
select pg_temp.expect_error($$select public.request_concepts('bbbbbbbb-0000-0000-0000-000000000001', 'third', 2)$$, '%already in progress%');
select public.cancel_concepts(pg_temp.id('r2'));
select pg_temp.check((select status = 'canceled' from public.concept_rounds where id = pg_temp.id('r2')), 'queued round canceled');

-- 2. Worker claims and completes; members only read.
select pg_temp.expect_error($$select public.claim_concept_round('w1')$$, '%permission denied%');
select pg_temp.as_worker();
select pg_temp.check((select id = pg_temp.id('r1') and status = 'generating' and attempts = 1 from public.claim_concept_round('w1')), 'claimed');
select pg_temp.check((select public.claim_concept_round('w2') is null or (public.claim_concept_round('w2')).id is null), 'nothing else queued');
select pg_temp.expect_error($$select public.complete_concept_round(pg_temp.id('r1'), 'w2', '{}', null, 'fixture', 'fixture-1', '[]')$$, '%not being generated by w2%');
select pg_temp.expect_error($$select public.complete_concept_round(pg_temp.id('r1'), 'w1', '{}', null, 'fixture', 'fixture-1',
  pg_temp.variants('bbbbbbbb-0000-0000-0000-000000000002', 1))$$, '%project''s folder%');
select pg_temp.check((select public.complete_concept_round(pg_temp.id('r1'), 'w1', '{"envelope": {"length_mm": 160}}', 'offline', 'fixture', 'fixture-1',
  pg_temp.variants('bbbbbbbb-0000-0000-0000-000000000001', 2)
  || jsonb_build_array(jsonb_build_object('ordinal', 3, 'name', 'Variant 3', 'prompt', 'p', 'status', 'failed', 'error', 'blocked by provider safety filter')))
  = 'partial'), 'two of three images: partial');
insert into ids select 'v1', id from public.concept_variants where round_id = pg_temp.id('r1') and ordinal = 1;
insert into ids select 'v3', id from public.concept_variants where round_id = pg_temp.id('r1') and ordinal = 3;
select pg_temp.act_as('00000000-0000-0000-0000-00000000000e');   -- viewer reads
select pg_temp.check((select count(*) = 3 from public.concept_variants where round_id = pg_temp.id('r1')), 'members see the variants');
update public.concept_variants set name = 'x' where id = pg_temp.id('v1');
select pg_temp.check((select name = 'Variant 1' from public.concept_variants where id = pg_temp.id('v1')), 'members cannot edit variants');
select pg_temp.act_as('00000000-0000-0000-0000-00000000000b');
select pg_temp.check((select count(*) = 0 from public.concept_variants), 'outsiders see none');

-- 3. Refinement must start from a finished variant of the same project.
select pg_temp.act_as('00000000-0000-0000-0000-00000000000f');
select pg_temp.expect_error($$select public.request_concepts('bbbbbbbb-0000-0000-0000-000000000001', 'more grip', 2, pg_temp.id('v3'))$$, '%finished concept of this project%');
insert into ids select 'r3', public.request_concepts('bbbbbbbb-0000-0000-0000-000000000001', 'More grip on the sides', 2, pg_temp.id('v1'));
select pg_temp.check((select parent_variant_id = pg_temp.id('v1') and round_no = 3 from public.concept_rounds where id = pg_temp.id('r3')), 'refinement round');

-- 4. Design freeze: owners, reviewers and clients; envelope required; a decision is recorded.
select pg_temp.act_as('00000000-0000-0000-0000-00000000000c');   -- engineers cannot sign off the look
select pg_temp.expect_error($$select public.freeze_design(pg_temp.id('v1'), '{"length_mm": 160, "width_mm": 90, "height_mm": 28}', '{}')$$, '%only owners, reviewers and clients%');
select pg_temp.act_as('00000000-0000-0000-0000-00000000000f');
select pg_temp.expect_error($$select public.freeze_design(pg_temp.id('v3'), '{"length_mm": 160, "width_mm": 90, "height_mm": 28}', '{}')$$, '%finished concept%');
select pg_temp.expect_error($$select public.freeze_design(pg_temp.id('v1'), '{"length_mm": 160, "width_mm": 90}', '{}')$$, '%length, width and height%');
select pg_temp.expect_error($$select public.freeze_design(pg_temp.id('v1'), '{"length_mm": "x", "width_mm": 90, "height_mm": 28}', '{}')$$, '%length, width and height%');
select pg_temp.expect_error($$select public.freeze_design(pg_temp.id('v1'), '{"length_mm": -1, "width_mm": 90, "height_mm": 28}', '{}')$$, '%length, width and height%');
insert into ids select 'f1', public.freeze_design(pg_temp.id('v1'), '{"length_mm": 160, "width_mm": 90, "height_mm": 28}',
  '{"summary": "matte black PC/ABS, orange buttons"}', 'Approved at the review call');
select pg_temp.check((select d.decision_class = 'mechanical' and d.title = 'Design freeze: Variant 1'
                        and d.statement like '%160 x 90 x 28 mm%matte black PC/ABS%'
                        and d.evidence_refs -> 0 ->> 'note' = 'concept image, not CAD'
                      from public.design_freezes f join public.decisions d on d.id = f.decision_id where f.id = pg_temp.id('f1')),
  'freeze recorded as a decision citing the concept image');
select pg_temp.check((select count(*) = 1 from public.current_design_freeze where project_id = 'bbbbbbbb-0000-0000-0000-000000000001'), 'one current freeze');

-- 5. Change control: a second freeze needs a reason and supersedes the first (and its decision).
select pg_temp.act_as('00000000-0000-0000-0000-00000000000a');   -- owner
insert into ids select 'v2', id from public.concept_variants where round_id = pg_temp.id('r1') and ordinal = 2;
select pg_temp.expect_error($$select public.freeze_design(pg_temp.id('v2'), '{"length_mm": 150, "width_mm": 85, "height_mm": 26}', '{}')$$, '%reason for changing it%');
insert into ids select 'f2', public.freeze_design(pg_temp.id('v2'), '{"length_mm": 150, "width_mm": 85, "height_mm": 26}', '{}', null,
  'Battery shrank; client prefers the slimmer variant');
select pg_temp.check((select supersedes_id = pg_temp.id('f1') from public.design_freezes where id = pg_temp.id('f2')), 'new freeze supersedes the old');
select pg_temp.check((select array_agg(variant_id) = array[pg_temp.id('v2')] from public.current_design_freeze
                      where project_id = 'bbbbbbbb-0000-0000-0000-000000000001'), 'only the new freeze is current');
select pg_temp.check((select count(*) = 1 from public.current_decisions where title like 'Design freeze:%'
                      and project_id = 'bbbbbbbb-0000-0000-0000-000000000001'), 'old freeze decision superseded');
select pg_temp.act_as(null);
select pg_temp.expect_error($$update public.design_freezes set note = 'x' where id = pg_temp.id('f1')$$, '%immutable%');
select pg_temp.check((select count(*) = 1 from public.audit_events where event_type = 'design.freeze_changed'
                      and payload ->> 'reason' like 'Battery shrank%'), 'change audited with the reason');

-- 6. Rate limit: 12 rounds per project per day.
select pg_temp.as_worker();
update public.concept_rounds set status = 'ready' where project_id = 'bbbbbbbb-0000-0000-0000-000000000001' and status in ('queued', 'generating');
insert into public.concept_rounds (project_id, round_no, direction, variant_count, status)
select 'bbbbbbbb-0000-0000-0000-000000000001', 100 + i, 'filler', 1, 'ready' from generate_series(1, 9) i;
select pg_temp.act_as('00000000-0000-0000-0000-00000000000f');
select pg_temp.expect_error($$select public.request_concepts('bbbbbbbb-0000-0000-0000-000000000001', 'one more', 1)$$, '%12 concept rounds%');
select pg_temp.act_as(null);

\echo 'All concept tests passed.'
