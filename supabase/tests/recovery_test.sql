-- Recovery (G6): for every lease-based job, a worker that dies mid-job loses it after the lease goes stale; another
-- worker takes it over; the dead worker's late result is refused (fenced); after 3 attempts the job gives up instead
-- of looping. The task queue (G2) is covered by worker_test.sql.
\set ON_ERROR_STOP on
\o /dev/null

create function pg_temp.expect_error(p_sql text, p_like text) returns void language plpgsql as $$
declare v_err text;
begin
  begin execute p_sql; exception when others then v_err := sqlerrm; end;
  if v_err is null then raise exception 'statement should have failed but succeeded: %', p_sql;
  elsif v_err not like p_like then raise exception 'expected error like "%", got "%"', p_like, v_err; end if;
end;
$$;
create function pg_temp.check(p_ok boolean, p_msg text) returns void language plpgsql as $$
begin if not coalesce(p_ok, false) then raise exception 'check failed: %', p_msg; end if; end;
$$;
create temp table ids (name text primary key, id uuid);
grant all on ids to service_role;

-- Fresh jobs of each kind, queued.
with x as (insert into public.concept_rounds (project_id, round_no, direction, variant_count)
  values ('bbbbbbbb-0000-0000-0000-000000000001', 900, 'recovery test', 1) returning id) insert into ids select 'concept', id from x;
with x as (insert into public.rfqs (project_id, rfq_no, title, category, status)
  values ('bbbbbbbb-0000-0000-0000-000000000001', 900, 'recovery test', 'pcba', 'packaging') returning id) insert into ids select 'rfq', id from x;
with x as (insert into public.flux_audits (project_id, audit_no, title, status, requested_at)
  values ('bbbbbbbb-0000-0000-0000-000000000001', 900, 'recovery test', 'queued', now() - interval '1 day') returning id) insert into ids select 'flux', id from x;
-- Nothing else may be waiting in these queues for this test to be exact.
update public.concept_rounds set status = 'canceled' where status in ('queued', 'generating') and id <> (select id from ids where name = 'concept');
update public.rfqs set status = 'draft', claimed_by = null where status = 'packaging' and id <> (select id from ids where name = 'rfq');
update public.flux_audits set status = 'failed' where status in ('queued', 'running') and id <> (select id from ids where name = 'flux');

set role service_role;
-- 1. w1 claims everything, then "dies".
select pg_temp.check((select (public.claim_concept_round('w1')).id = (select id from ids where name = 'concept')), 'concept claimed by w1');
select pg_temp.check((select (public.claim_rfq_packet('w1')).id = (select id from ids where name = 'rfq')), 'rfq claimed by w1');
select pg_temp.check((select (public.claim_flux_audit('w1')).id = (select id from ids where name = 'flux')), 'flux claimed by w1');
-- While w1's lease is fresh, nobody else gets the work.
select pg_temp.check((select (public.claim_concept_round('w2')).id is null), 'concept not handed out twice');
select pg_temp.check((select (public.claim_rfq_packet('w2')).id is null), 'rfq not handed out twice');
select pg_temp.check((select (public.claim_flux_audit('w2')).id is null), 'flux not handed out twice');
reset role;
update public.concept_rounds set claimed_at = now() - interval '2 hours' where id = (select id from ids where name = 'concept');
update public.rfqs set claimed_at = now() - interval '2 hours' where id = (select id from ids where name = 'rfq');
update public.flux_audits set claimed_at = now() - interval '2 hours' where id = (select id from ids where name = 'flux');

-- 2. w2 takes over the stale leases.
set role service_role;
select pg_temp.check((select c.id = (select id from ids where name = 'concept') and c.attempts = 2 and c.claimed_by = 'w2' from public.claim_concept_round('w2') c), 'concept taken over');
select pg_temp.check((select c.id = (select id from ids where name = 'rfq') and c.attempts = 2 and c.claimed_by = 'w2' from public.claim_rfq_packet('w2') c), 'rfq taken over');
select pg_temp.check((select c.id = (select id from ids where name = 'flux') and c.attempts = 2 and c.claimed_by = 'w2' from public.claim_flux_audit('w2') c), 'flux taken over');

-- 3. w1 comes back late: its results are refused.
select pg_temp.expect_error($$select public.complete_concept_round((select id from ids where name = 'concept'), 'w1', '{}', 'm', 'p', 'm', '[]')$$, '%not being generated by w1%');
select pg_temp.expect_error($$select public.complete_rfq_packet((select id from ids where name = 'rfq'), 'w1', 'bbbbbbbb-0000-0000-0000-000000000001/rfq/x.zip', repeat('a', 64), '[]')$$, '%not being packaged by w1%');
select pg_temp.expect_error($$select public.complete_flux_audit((select id from ids where name = 'flux'), 'w1', 'bbbbbbbb-0000-0000-0000-000000000001/flux/r.json', 'bbbbbbbb-0000-0000-0000-000000000001/flux/r.md', repeat('a', 64), '{}', 'm')$$, '%not being run by w1%');

-- 4. w2 finishes normally.
select public.complete_rfq_packet((select id from ids where name = 'rfq'), 'w2', 'bbbbbbbb-0000-0000-0000-000000000001/rfq/x.zip', repeat('a', 64), '[]');
select public.complete_flux_audit((select id from ids where name = 'flux'), 'w2', 'bbbbbbbb-0000-0000-0000-000000000001/flux/r.json', 'bbbbbbbb-0000-0000-0000-000000000001/flux/r.md', repeat('a', 64), '{}', 'm');
reset role;
select pg_temp.check((select status = 'ready' from public.rfqs where id = (select id from ids where name = 'rfq')), 'rfq completed by w2');
select pg_temp.check((select status = 'ready' from public.flux_audits where id = (select id from ids where name = 'flux')), 'flux completed by w2');

-- 5. A job that keeps killing its workers gives up after 3 attempts instead of looping.
update public.concept_rounds set attempts = 3, claimed_at = now() - interval '2 hours' where id = (select id from ids where name = 'concept');
set role service_role;
select pg_temp.check((select (public.claim_concept_round('w3')).id is null), 'poison job not handed out again');
reset role;
select pg_temp.check((select status = 'failed' and error like 'gave up after 3 attempts%' from public.concept_rounds where id = (select id from ids where name = 'concept')), 'gave up');

\echo 'All recovery tests passed.'
